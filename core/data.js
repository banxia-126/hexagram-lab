// 旬空：由日干支推出本旬空亡的两个地支
export function xunKong(dayGanZhi) {
  const g = GAN.indexOf(dayGanZhi[0]), z = ZHI.indexOf(dayGanZhi[1]);
  let idx = 0;
  for (let i = 0; i < 60; i++) if (i % 10 === g && i % 12 === z) { idx = i; break; }
  const sz = Math.floor(idx / 10) * 10 % 12;
  return [ZHI[(sz + 10) % 12], ZHI[(sz + 11) % 12]];
}

// 六亲：以卦宫五行为“我”
export function liuQin(gongWx, zhi) {
  const zw = ZHI_WX[zhi];
  if (zw === gongWx) return '兄弟';
  if (SHENG[gongWx] === zw) return '子孙';
  if (KE[gongWx] === zw) return '妻财';
  if (KE[zw] === gongWx) return '官鬼';
  return '父母';
}

// 十二时辰：子=1 … 亥=12
export const hourToZhi = (h) => (h >= 23 || h < 1) ? 1 : Math.floor((h + 1) / 2) + 1;

// 时柱：五鼠遁 ——
//   甲己还加甲、乙庚丙作初、丙辛从戊起、丁壬庚子居、戊癸何方发、壬子是真途
// 即 时干序 =（日干序 % 5）× 2 + 时支序。hourZhi 按 hourToZhi 的约定 1..12。
//
// 不用 lunar.js 的 getTimeInGanZhi()：它内部取的是 23:00 换日的日干，
// 而本工具已经用「晚子时」设置自己挪过一次日期了，再取它会二次位移；
// 何况那个 Lunar 是无时分建的，时辰恒为子。由本工具认定的日柱推，
// 日柱与时柱才永远自洽。
export const shiGanZhi = (dayGanZhi, hourZhi) =>
  GAN[((GAN.indexOf(dayGanZhi[0]) % 5) * 2 + hourZhi - 1) % 10] + ZHI[hourZhi - 1];

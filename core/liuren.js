// 月、日、时辰各从 1 起
export function qike(month, day, hourZhi, wuxing = 'shen') {
  const pos = (month - 1 + day - 1 + hourZhi - 1) % 6;
  const 宫 = GONG[pos];
  const 五行 = WUXING[wuxing] ? WUXING[wuxing][宫] : WUXING.shen[宫];
  const [方位, 色] = FANGWEI[五行];
  return {
    宫, 序: pos + 1, ...GONG_INFO[宫], 五行, 方位, 色, 五行派: wuxing,
    月: month, 日: day, 时辰: hourZhi,
  };
}

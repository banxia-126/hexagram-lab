// 找不到城市时手输经度用：把输入框里的字符串变成合法经度，非法返回 null
export function parseLon(s) {
  const v = parseFloat(String(s).trim());
  if (!Number.isFinite(v) || v < -180 || v > 180) return null;
  return Math.round(v * 100) / 100;
}

// 经度的中文写法，西经要显示成「西经」
export const lonLabel = (v) => {
  const d = Math.abs(v).toFixed(2).replace(/\.?0+$/, '');
  if (v === 0) return '0°';
  return (v > 0 ? '东经 ' : '西经 ') + d + '°';
};
